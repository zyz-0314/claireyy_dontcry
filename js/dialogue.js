  var MOODS = [
    { key: 'happy',  emoji: '☀',  label: '有点开心' },
    { key: 'plain',  emoji: '☁',  label: '就还好' },
    { key: 'sad',    emoji: '🌧',  label: '难过' },
    { key: 'tired',  emoji: '🌙',  label: '很累' },
    { key: 'angry',  emoji: '⚡',  label: '生气' },
    { key: 'lonely', emoji: '🫧',  label: '有点孤单' },
    { key: 'blank',  emoji: '·',   label: '不想说' },
  ];

  // 没有选心情时的落点。文案库的「普通/平淡」正是为这种时刻写的，
  // 它自己就说了「不说话也可以」——所以留空不是错误状态。
  var DEFAULT_MOOD = 'plain';
  var RARE_CHANCE = 0.06;

  var byKey = {};
  for (var i = 0; i < MOODS.length; i++) byKey[MOODS[i].key] = MOODS[i];

  function moodInfo(key) { return byKey[key] || byKey[DEFAULT_MOOD]; }

  // 每条回复随机取；记住每个分类上一次用的是哪条，避免连着两次撞同一句
  // （连着撞会立刻暴露「这是随机文案」，陪伴感就断了）。
  var lastPick = {};

  function pickFrom(pool, bucket) {
    if (!pool || !pool.length) return null;
    if (pool.length === 1) return pool[0];
    var idx = Math.floor(Math.random() * pool.length);
    if (lastPick[bucket] === idx) idx = (idx + 1 + Math.floor(Math.random() * (pool.length - 1))) % pool.length;
    lastPick[bucket] = idx;
    return pool[idx];
  }

  // 一次回应的完整台词：先掷彩蛋，没中就走心情分类。
  // 返回 { lines: [...], rare: bool, mood: key }
  function respond(moodKey) {
    var info = moodInfo(moodKey);
    if (Math.random() < RARE_CHANCE) {
      return { lines: pickFrom(RARE, 'rare'), rare: true, mood: info.key };
    }
    return { lines: pickFrom(RESPONSES[info.key], info.key), rare: false, mood: info.key };
  }

  function opening(index, name) {
    var lines = OPENINGS[index % OPENINGS.length];
    return lines.map(function (l) { return l.replace('{name}', name); });
  }

  // 「最近的小情绪天气」用：按心情计数，只数数，不做分析。
  // 返回按出现次数倒序的 [{ emoji, label, count }]。
  function weather(entries) {
    var tally = {};
    for (var i = 0; i < entries.length; i++) {
      var k = (entries[i] && entries[i].mood) || DEFAULT_MOOD;
      if (!byKey[k]) k = DEFAULT_MOOD;
      tally[k] = (tally[k] || 0) + 1;
    }
    var out = [];
    for (var key in tally) {
      if (!Object.prototype.hasOwnProperty.call(tally, key)) continue;
      out.push({ emoji: byKey[key].emoji, label: byKey[key].label, key: key, count: tally[key] });
    }
    out.sort(function (a, b) { return b.count - a.count; });
    return out;
  }

